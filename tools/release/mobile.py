"""Configure native Godot phone builds. Signing credentials come from environment variables.

Run from any directory: python tools/release/mobile.py --help
Godot, its export templates, and the platform SDK must already be installed.
"""

import argparse
import json
import os
from pathlib import Path
import platform
import re
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
CONFIG = Path(__file__).with_name("mobile.json")
TEMPLATE = Path(__file__).with_name("export_presets.cfg.in")
MARKER = "; Generated by tools/release/mobile.py"
TARGETS = {
    "android-apk": ("Android Test", "exports/android/dust-in-space-test.apk"),
    "android-aab": ("Android Play", "exports/android/dust-in-space.aab"),
    "ios": ("iOS", "exports/ios/dust_in_space.ipa"),
}


def settings(app_id: str | None = None) -> dict:
    data = json.loads(CONFIG.read_text(encoding="utf-8"))
    data["app_id"] = app_id or data["app_id"]
    if not re.fullmatch(r"[a-z][a-z0-9]*(?:\.[a-z][a-z0-9]*){2,}", data["app_id"]):
        raise ValueError("App ID must be a lowercase reverse-domain identifier, e.g. com.owner.dustinspace")
    if not re.fullmatch(r"\d+\.\d+\.\d+", data["version"]):
        raise ValueError("Version must have three numeric components")
    if type(data["build"]) is not int or not 0 < data["build"] < 2100000000:
        raise ValueError("Build must be a positive Android/iOS build number")
    return data


def render_presets(data: dict, team_id: str = "") -> str:
    if team_id and not re.fullmatch(r"[A-Z0-9]{10}", team_id):
        raise ValueError("Apple Team ID must be 10 uppercase letters/digits")
    text = TEMPLATE.read_text(encoding="utf-8")
    for key, value in {**data, "ios_team_id": team_id}.items():
        text = text.replace("@" + key.upper() + "@", str(value))
    if re.search(r"@[A-Z_]+@", text):
        raise ValueError("Unresolved export-preset field")
    return text


def configure(data: dict, team_id: str) -> None:
    target = ROOT / "export_presets.cfg"
    content = render_presets(data, team_id)
    if target.exists():
        old = target.read_text(encoding="utf-8")
        if old == content:
            return
        if not old.startswith(MARKER):
            backup = ROOT / "output/release/original_export_presets.cfg"
            backup.parent.mkdir(parents=True, exist_ok=True)
            if backup.exists():
                raise ValueError("Existing presets are not generated; backup already exists. Preserve them before configuring.")
            shutil.copy2(target, backup)
            print("Preserved previous local presets in output/release/original_export_presets.cfg")
    target.write_text(content, encoding="utf-8", newline="\n")
    print("Configured Android Test, Android Play and iOS presets")


def run_godot(godot: str, args: list[str]) -> None:
    logs = ROOT / "output/release"
    logs.mkdir(parents=True, exist_ok=True)
    subprocess.run([godot, "--headless", "--path", str(ROOT), "--log-file",
                    str(logs / "godot-export.log"), *args], cwd=ROOT, check=True)


def expected_output(command: str, destination: Path) -> Path:
    # Godot's project-only export creates the project beside the requested .ipa; no IPA is built.
    if command == "ios":
        return destination.with_suffix(".xcodeproj") / "project.pbxproj"
    return destination


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=["configure", *TARGETS])
    parser.add_argument("--app-id", help="Override the provisional ID in mobile.json (confirm before store upload)")
    parser.add_argument("--ios-team-id", default=os.environ.get("DUST_IOS_TEAM_ID", ""))
    parser.add_argument("--godot", default=os.environ.get("GODOT", "godot"), help="Godot 4.7 editor executable")
    args = parser.parse_args()
    data = settings(args.app_id)
    if args.command == "ios":
        if platform.system() != "Darwin":
            raise ValueError("iOS export needs macOS with Xcode. Run this command on your friend's Mac or a Mac runner.")
        if not args.ios_team_id:
            raise ValueError("Set DUST_IOS_TEAM_ID or pass --ios-team-id (Apple Developer > Membership details)")
    if args.command == "android-aab":
        required = ["GODOT_ANDROID_KEYSTORE_RELEASE_PATH", "GODOT_ANDROID_KEYSTORE_RELEASE_USER",
                    "GODOT_ANDROID_KEYSTORE_RELEASE_PASSWORD"]
        missing = [key for key in required if not os.environ.get(key)]
        if missing:
            raise ValueError("Release signing requires environment variables: " + ", ".join(missing))
        if not Path(os.environ[required[0]]).is_file():
            raise ValueError("Release keystore path does not exist")
    godot = shutil.which(args.godot)
    if args.command != "configure" and not godot:
        raise ValueError("Godot is not on PATH; use --godot /path/to/Godot")
    if args.command != "configure":
        version = subprocess.check_output([godot, "--version"], text=True).strip()
        if not version.startswith(data["godot_version"] + "."):
            raise ValueError(f"Expected Godot {data['godot_version']}, found {version}")
    configure(data, args.ios_team_id)
    if args.command == "configure":
        return 0
    preset, relative = TARGETS[args.command]
    destination = ROOT / relative
    destination.parent.mkdir(parents=True, exist_ok=True)
    run_godot(godot, ["--import"])
    options = ["--export-debug" if args.command == "android-apk" else "--export-release", preset, str(destination)]
    if args.command == "android-aab" and not (ROOT / "android/build/build.gradle").is_file():
        options.insert(0, "--install-android-build-template")
    run_godot(godot, options)
    artifact = expected_output(args.command, destination)
    if not artifact.is_file():
        raise ValueError(f"Godot returned without creating {artifact.relative_to(ROOT)}; see output/release/godot-export.log")
    print(f"Built {artifact.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (ValueError, OSError, subprocess.CalledProcessError) as error:
        print(f"Mobile build: {error}", file=sys.stderr)
        sys.exit(1)
